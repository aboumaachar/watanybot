export function normalizeDaleelArabic(value: string): string {
  return String(value || "").toLowerCase()
    .normalize("NFKC").replace(/[\u064b-\u065f\u0670\u0640]/g, "")
    .replace(/[إأٱآ]/g, "ا").replace(/ى/g, "ي").replace(/ة/g, "ه")
    .replace(/ؤ/g, "و").replace(/ئ/g, "ي")
    .replace(/اال/g, "ال").replace(/[^a-z0-9\u0621-\u064a]+/g, " ")
    .replace(/\s+/g, " ").trim();
}
const SEARCH_STOPWORDS = new Set(["في", "من", "على", "الى", "عن", "التي", "الذي", "حول", "عند", "اجراءات", "طلب", "طلبات", "الجيش", "لدى", "المتقاعد", "المتقاعدين", "العسكري", "العسكريين"]);
function tokens(value: string): string[] {
  return Array.from(new Set(normalizeDaleelArabic(value).split(" ").filter((w) => w.length >= 3 && !SEARCH_STOPWORDS.has(w))));
}
export function findAcceptedGreenDaleelTopic(query: string): DaleelTopic | null {
  const normalized = normalizeDaleelArabic(query);
  const entry = ACCEPTED_GREEN_SEARCH_ALIASES.find(([, alias]) => normalizeDaleelArabic(alias) === normalized);
  return entry ? getDaleelTopic(entry[0]) : null;
}
export function searchDaleelTopics(query: string): DaleelTopic[] {
  const q = normalizeDaleelArabic(query);
  if (!q || q.length < 4) return [];
  if (findAcceptedGreenDaleelTopic(query)) return [];
  const qTokens = tokens(query);
  return DALEEL_APRIL_2026_TOPICS.filter((t) => !t.acceptedGreen).map((topic) => {
    const name = normalizeDaleelArabic(topic.title);
    const words = tokens(topic.title);
    const shared = qTokens.filter((w) => words.some((item) => item === w || (w.length > 4 && item.length > 4 && (item.includes(w) || w.includes(item))))).length;
    const f1 = shared ? (2 * shared / (qTokens.length + words.length)) : 0;
    const score = q === name ? 1 : (q.includes(name) || name.includes(q)) && Math.min(q.length, name.length) >= 14 ? 0.92 : f1;
    return { topic, score };
  }).filter((item) => item.score >= 0.53).sort((a,b) => b.score - a.score || a.topic.guideNo - b.topic.guideNo).slice(0, 6).map((item) => item.topic);
}
export function getDaleelTopic(guideNo: number): DaleelTopic | null {
  return DALEEL_APRIL_2026_TOPICS.find((item) => item.guideNo === guideNo) || null;
}
