import { chromium } from 'playwright';
const browser = await chromium.launch({ headless: true, args: ['--no-sandbox'] });
const page = await browser.newPage({ viewport: { width: 1280, height: 900 } });
const requests = [];
page.on('request', r => { if (r.method() === 'POST') requests.push(r.url()); });
await page.goto('https://koudama.com/chat', { waitUntil: 'networkidle', timeout: 30000 });
const composer = page.getByLabel('اكتب سؤالك إلى مساعد موطني');
const composerCount = await composer.count();
const before = await page.locator('body').innerText();
await composer.fill('مسا الخير');
const responsePromise = page.waitForResponse(r => r.url().includes('/api/chat/stream') && r.request().method() === 'POST', { timeout: 30000 });
await page.getByRole('button', { name: 'إرسال', exact: true }).click();
const response = await responsePromise;
await page.waitForTimeout(1200);
const after = await page.locator('body').innerText();
const canonicalRequests = requests.filter(u => u.includes('/api/chat/stream') || /\/api\/chat(?:\?|$)/.test(u));
const hybridRequests = requests.filter(u => u.includes('/api/chat/hybrid') || u.includes('/api/kb/hybrid-chat'));
const failures = [];
if (composerCount !== 1) failures.push(`composerCount=${composerCount}`);
if (response.status() !== 200) failures.push(`streamStatus=${response.status()}`);
if (canonicalRequests.length < 1) failures.push('canonicalRequestMissing');
if (hybridRequests.length !== 0) failures.push(`hybridRequests=${hybridRequests.length}`);
if (!after.includes('مسا الخير') || after.length <= before.length) failures.push('assistantUiDidNotAdvance');
console.log(JSON.stringify({ status: failures.length ? 'FAIL' : 'PASS', composerCount, streamStatus: response.status(), canonicalRequests, hybridRequests, uiDeltaChars: after.length - before.length, failures }, null, 2));
await browser.close();
process.exitCode = failures.length ? 71 : 0;
